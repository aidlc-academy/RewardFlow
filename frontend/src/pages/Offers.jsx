import { useState, useEffect } from 'react';
import { Tag, RefreshCw, Filter, Info, Sparkles } from 'lucide-react';
import { api, formatDate } from '../api/index.js';
import { PageLoader } from '../components/LoadingSpinner.jsx';

const OFFER_META = {
  welcome:  { icon: '🎉', gradient: 'from-emerald-50 to-teal-50',   border: 'border-emerald-200', text: 'text-emerald-800', tag: 'bg-emerald-100 text-emerald-700' },
  comeback: { icon: '👋', gradient: 'from-blue-50 to-indigo-50',     border: 'border-blue-200',    text: 'text-blue-800',    tag: 'bg-blue-100 text-blue-700' },
  grocery:  { icon: '🛒', gradient: 'from-green-50 to-emerald-50',   border: 'border-green-200',   text: 'text-green-800',   tag: 'bg-green-100 text-green-700' },
  cafe:     { icon: '☕', gradient: 'from-amber-50 to-orange-50',    border: 'border-amber-200',   text: 'text-amber-800',   tag: 'bg-amber-100 text-amber-700' },
  premium:  { icon: '⭐', gradient: 'from-violet-50 to-purple-50',   border: 'border-violet-200',  text: 'text-violet-800',  tag: 'bg-violet-100 text-violet-700' },
  repeat:   { icon: '🔄', gradient: 'from-indigo-50 to-blue-50',     border: 'border-indigo-200',  text: 'text-indigo-800',  tag: 'bg-indigo-100 text-indigo-700' },
};
const DEFAULT_META = { icon: '🎁', gradient: 'from-gray-50 to-slate-50', border: 'border-gray-200', text: 'text-gray-800', tag: 'bg-gray-100 text-gray-600' };

function getInitialColor(name) {
  const c = ['from-indigo-400 to-violet-500','from-emerald-400 to-teal-500','from-amber-400 to-orange-500','from-pink-400 to-rose-500','from-blue-400 to-cyan-500'];
  return c[(name?.charCodeAt(0) || 0) % c.length];
}

export default function Offers() {
  const [offers, setOffers] = useState([]);
  const [customers, setCustomers] = useState([]);
  const [filterCustomer, setFilterCustomer] = useState('');
  const [filterType, setFilterType] = useState('');
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);

  const loadOffers = (custId = filterCustomer, type = filterType) => {
    const params = {};
    if (custId) params.customerId = custId;
    if (type) params.offerType = type;
    api.getOffers(params).then(r => setOffers(r.data)).catch(console.error).finally(() => setLoading(false));
  };

  useEffect(() => {
    api.getCustomers().then(r => setCustomers(r.data)).catch(console.error);
    loadOffers('', '');
  }, []);

  const handleFilterChange = (custId, type) => {
    setFilterCustomer(custId);
    setFilterType(type);
    setLoading(true);
    loadOffers(custId, type);
  };

  const handleGenerateAll = async () => {
    setGenerating(true);
    try {
      await Promise.all(customers.map(c => api.generateOffers(c.id)));
      loadOffers('', '');
    } catch (e) { console.error(e); }
    setGenerating(false);
  };

  // Group by customer
  const grouped = {};
  offers.forEach(o => {
    if (!grouped[o.customer_id]) {
      grouped[o.customer_id] = { name: o.customer_name, phone: o.customer_phone, id: o.customer_id, offers: [] };
    }
    grouped[o.customer_id].offers.push(o);
  });
  const groups = Object.values(grouped);

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-start justify-between">
        <div>
          <h1 className="page-title">Personalised Offers</h1>
          <p className="page-subtitle">Rule-based recommendations from purchase behaviour</p>
        </div>
        <button onClick={handleGenerateAll} disabled={generating} className="btn-secondary">
          <RefreshCw className={`w-4 h-4 ${generating ? 'animate-spin' : ''}`} />
          {generating ? 'Regenerating...' : 'Refresh All'}
        </button>
      </div>

      {/* Transparency banner */}
      <div className="flex items-start gap-3 p-4 bg-blue-50 border border-blue-100 rounded-xl text-sm text-blue-700">
        <Info className="w-4 h-4 text-blue-400 flex-shrink-0 mt-0.5" />
        <p><strong>Fully transparent:</strong> Every offer is generated by deterministic rules — no black-box AI. Each card shows exactly which rule triggered it and why.</p>
      </div>

      {/* Filters */}
      <div className="card py-4">
        <div className="flex items-center gap-3 flex-wrap">
          <Filter className="w-4 h-4 text-gray-400 flex-shrink-0" />
          <select
            value={filterCustomer}
            onChange={e => handleFilterChange(e.target.value, filterType)}
            className="form-input max-w-xs"
          >
            <option value="">All Customers</option>
            {customers.map(c => <option key={c.id} value={c.id}>{c.name}</option>)}
          </select>
          <select
            value={filterType}
            onChange={e => handleFilterChange(filterCustomer, e.target.value)}
            className="form-input max-w-xs"
          >
            <option value="">All Types</option>
            {Object.entries({ welcome: '🎉 Welcome', comeback: '👋 Comeback', grocery: '🛒 Grocery', cafe: '☕ Café', premium: '⭐ Premium', repeat: '🔄 Repeat' }).map(([k,v]) => (
              <option key={k} value={k}>{v}</option>
            ))}
          </select>
          <span className="text-sm text-gray-400 font-medium ml-auto">
            <span className="font-bold text-gray-700">{offers.length}</span> offers across <span className="font-bold text-gray-700">{groups.length}</span> customers
          </span>
        </div>
      </div>

      {loading ? <PageLoader /> : groups.length === 0 ? (
        <div className="card text-center py-20">
          <div className="w-16 h-16 bg-gray-100 rounded-2xl flex items-center justify-center mx-auto mb-4">
            <Tag className="w-8 h-8 text-gray-300" />
          </div>
          <p className="font-semibold text-gray-600">No offers yet</p>
          <p className="text-sm text-gray-400 mt-1">Generate offers based on purchase patterns</p>
          <button onClick={handleGenerateAll} disabled={generating} className="btn-primary mt-5">
            <Sparkles className="w-4 h-4" /> Generate Offers for All Customers
          </button>
        </div>
      ) : (
        <div className="space-y-7">
          {groups.map(group => (
            <div key={group.id} className="card">
              {/* Customer header */}
              <div className="flex items-center gap-3 mb-5 pb-4 border-b border-gray-100">
                <div className={`w-11 h-11 bg-gradient-to-br ${getInitialColor(group.name)} rounded-xl flex items-center justify-center shadow-sm`}>
                  <span className="font-bold text-white">{group.name.charAt(0)}</span>
                </div>
                <div className="flex-1">
                  <p className="font-bold text-gray-900">{group.name}</p>
                  <p className="text-xs text-gray-400 mt-0.5">{group.phone}</p>
                </div>
                <span className="badge bg-indigo-50 text-indigo-600 border border-indigo-100">
                  {group.offers.length} offer{group.offers.length !== 1 ? 's' : ''}
                </span>
              </div>

              {/* Offer cards */}
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {group.offers.map(o => {
                  const m = OFFER_META[o.offer_type] || DEFAULT_META;
                  return (
                    <div key={o.id} className={`bg-gradient-to-br ${m.gradient} border ${m.border} rounded-xl p-4`}>
                      <div className="flex items-start gap-3">
                        <span className="text-2xl flex-shrink-0 leading-none mt-0.5">{m.icon}</span>
                        <div className="flex-1 min-w-0">
                          <p className={`font-bold text-sm ${m.text}`}>{o.title}</p>
                          <p className={`text-xs mt-1 leading-relaxed ${m.text} opacity-80`}>{o.description}</p>

                          {/* Reason box */}
                          <div className="mt-2.5 p-2.5 bg-white/70 rounded-lg">
                            <p className="text-xs text-gray-600 leading-relaxed">
                              <strong className="text-gray-700">Why:</strong> {o.reason}
                            </p>
                          </div>

                          <div className="flex items-center justify-between mt-2.5">
                            <span className={`text-xs px-2 py-0.5 rounded-full font-mono font-medium ${m.tag}`}>
                              {o.trigger_rule}
                            </span>
                            {o.valid_until && (
                              <span className={`text-xs ${m.text} opacity-50 font-medium`}>
                                Until {formatDate(o.valid_until)}
                              </span>
                            )}
                          </div>
                        </div>
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
